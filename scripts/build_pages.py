def table(id, headers, rows, filter=True, city_chips=False):
    tool = ''
    if filter:
        chips_html = ''
        if city_chips:
            chips = ['All', 'Shanghai', 'Beijing', 'Guangzhou', 'Chengdu']
            btns = ''.join(
                f'<button type="button" class="city-chip{" active" if c == "All" else ""}" '
                f'data-city-filter="{id}" data-city="{"" if c == "All" else c}" '
                f'aria-pressed="{"true" if c == "All" else "false"}">{c}</button>'
                for c in chips
            )
            chips_html = f'<div class="city-chips" role="group" aria-label="Filter {e(id)} by city">{btns}</div>'
        tool = (
            f'{chips_html}<div class="toolbar"><label for="{id}-search">Search these records</label>'
            f'<input id="{id}-search" data-filter="{id}" type="search" placeholder="City, venue, cuisine, hours or review flag…">'
            f'<span id="{id}-count" role="status">{len(rows)} of {len(rows)} rows shown</span></div>'
        )
    head = ''.join(f'<th scope="col" data-sort><button type="button">{e(h)} <span aria-hidden="true">↕</span></button></th>' for h in headers)
    body_rows = ''.join('<tr>' + ''.join(f'<td>{v}</td>' for v in row) + '</tr>' for row in rows)
    return (
        tool
        + '<p class="table-hint">Scroll horizontally for all columns. Use column headers to sort; blank values stay last.</p>'
        + f'<div class="table-wrap" tabindex="0" role="region" aria-label="{e(id)} comparison">'
        + f'<table id="{id}" data-sortable><caption class="sr-only">{e(id)} records with official source links, social reviews and review flags</caption>'
        + f'<thead><tr>{head}</tr></thead><tbody>{body_rows}</tbody></table></div>'
    )

