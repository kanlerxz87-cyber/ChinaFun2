# 10. Entry audit
def inline(s):
    s = e(s)
    s = re.sub(r'\[([^\]]+)\]\((https://[^\s)]+)\)', r'<a href="\2" target="_blank" rel="noopener noreferrer">\1</a>', s)
    return re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', s)

parts = []
labels = None
for line in (P / 'research/entry-audit.md').read_text().splitlines():
    if line.startswith('#'):
        n = min(len(line) - len(line.lstrip('#')), 4)
        parts.append(f'<h{n}>' + inline(line.lstrip('# ')) + f'</h{n}>')
        labels = None
    elif line.startswith('|'):
        cells = [v.strip() for v in line.strip('|').split('|')]
        if all(re.fullmatch(r'[:\- ]+', v) for v in cells):
            continue
        if labels is None:
            labels = cells
            continue
        parts.append(
            '<section class="audit-row"><h3>' + inline(cells[0]) + '</h3><dl>'
            + ''.join('<dt>' + inline(label) + '</dt><dd>' + inline(value) + '</dd>' for label, value in zip(labels[1:], cells[1:]))
            + '</dl></section>'
        )
    elif line.strip():
        parts.append('<p>' + inline(line) + '</p>')
        labels = None

page('entry-audit.html', 'Entry, health & eligibility audit', 'Independent official-source audit; confirm personal passport, visa and duration eligibility before booking.', '<div class="card audit">' + ''.join(parts) + '</div>')

