def e(s):
    return html.escape(str(s), quote=True)

def link(url, label='Official source'):
    return f'<a href="{e(url)}" target="_blank" rel="noopener noreferrer">{e(label)} ↗</a>' if url else ''

def blank(s):
    return e(s) if s != '' and s is not None else '<span class="unknown" title="Not confirmed from the official source">—</span>'

def flags(x):
    return ' '.join(f'<a class="badge warn" href="flagged.html#{e(i)}">{e(i)}</a>' for i in x.get('flags', []))

def review_links(x):
    parts = []
    for r in x.get('reviews', []):
        cls = 'ok' if r.get('kind') == 'Official profile' else 'info'
        parts.append(
            f'<div class="review-item"><span class="badge {cls}">{e(r["platform"])} · {e(r["kind"])}</span> '
            f'{link(r["url"], r["label"])}</div>'
        )
    s_links = [link(u, f'{k.title()} search') for k, u in x.get('socials', {}).items()]
    if s_links:
        parts.append('<div class="review-fallback"><small>Search fallback:</small> ' + ' · '.join(s_links) + '</div>')
    return ''.join(parts) if parts else blank('')

